src = r"E:\godot\rogue_slg\locale\keys_unique.txt"
out = r"E:\godot\rogue_slg\locale\mt\fr.json"

raw = open(src, "rb").read()
enc = "utf-8-sig"
if raw.startswith(b"\xff\xfe") or raw.startswith(b"\xfe\xff"):
    enc = "utf-16"
keys = [None] * 385
pat = re.compile(r"^(\d+) '(.*)'$")
for line in raw.decode(enc).splitlines():
    m = pat.match(line)
    if m:
        keys[int(m.group(1))] = m.group(2)
assert all(k is not None for k in keys)

def ph(s):
    no_pp = s.replace("%%", "")
    return {
        "%s": no_pp.count("%s"),
        "%d": no_pp.count("%d"),
        "%%": s.count("%%"),
        "color": s.count("[color"),
        "color_end": s.count("[/color"),
        "img": s.count("[img="),
        "img_end": s.count("[/img"),
        "b": s.count("[b]"),
        "b_end": s.count("[/b]"),
        "nl": len(s.replace("\\n", "\n").split("\n")) - 1,
    }

bad = []
for i, (k, t) in enumerate(zip(keys, tr)):
    if ph(k) != ph(t):
        bad.append((i, ph(k), ph(t)))
if bad:
    for i, a, b in bad:
        print("MISMATCH", i, a, b)
    sys.exit(1)

json.dump(tr, open(out, "w", encoding="utf-8"), ensure_ascii=False, indent=0)
print("OK wrote", out)
